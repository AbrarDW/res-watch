# ------------------------------------------------------------ rendering
_VAR = re.compile(r"\{\{(\w+)\}\}")


def render(name: str, **values) -> str:
    text = (TEMPLATES / name).read_text(encoding="utf-8")

    def sub(m):
        if m.group(1) not in values:
            raise KeyError(f"template {name}: missing value {m.group(1)}")
        return str(values[m.group(1)])
    return _VAR.sub(sub, text)


@dataclass
class Out:
    path: Path
    content: str
    what: str
    mode: int | None = None
    ask: bool = True          # show a diff and ask before overwriting a changed file


@dataclass
class Plan:
    files: list[Out] = field(default_factory=list)
    steps: list[str] = field(default_factory=list)     # printed "next steps"
    commands: list[list[str]] = field(default_factory=list)  # optional install commands (asked first)
    config: dict = field(default_factory=dict)
    set_password: bool = False


# --------------------------------------------------------------- prompts
NAMED_PROXIES = ("caddy", "nginx", "traefik", "apache", "cloudflare")


def question_keys(ans: dict) -> list[str]:
    """Every question the wizard will ask, in order, given the (known or assumed) answers."""
    keys = ["where"]
    where = ans.get("where")
    if where in ("vps", "both"):
        keys += ["run", "proxy"]
        proxy = ans.get("proxy") or "none"
        if proxy != "none":
            if proxy in NAMED_PROXIES:
                keys.append("domain")
            if proxy != "cloudflare":
                keys.append("https")
            keys.append("base_path")
        keys.append("auth")
    if where in ("local", "both"):
        keys += ["os", "start"]
    return keys


class Asker:
    def __init__(self, args, previous: dict):
        self.args, self.prev = args, previous
        self.file = read_toml(Path(args.answers)) if getattr(args, "answers", None) else {}
        self.answers: dict = {}
        self._prompted: set[str] = set()

    def progress(self, key: str) -> tuple[int, int]:
        """(X, Y) for "Question X of Y". Only questions that will actually be prompted are counted;
        branching answers not given yet are assumed to be their defaults, so Y can change as you answer."""
        assumed = {"where": self.prev.get("setup_where", "local"), "proxy": self.prev.get("setup_proxy", "none")}
        for k in assumed:
            if self._given(k) is not None:
                assumed[k] = self._given(k)
        keys = question_keys({**assumed, **self.answers})
        def prompted(k):
            if k in self.answers:          # already answered: count it only if we asked it
                return k in self._prompted
            return self._given(k) is None  # still to come: asked unless a flag/answers file covers it
        asked = [k for k in keys if prompted(k)]
        x = asked.index(key) + 1 if key in asked else len(asked)
        return x, len(asked)

    def _header(self, key: str) -> None:
        self._prompted.add(key)
        x, y = self.progress(key)
        print(f"\nQuestion {x} of {y}")

    def _given(self, key):
        attr = "os_" if key == "os" else key
        v = getattr(self.args, attr, None)
        return v if v is not None else self.file.get(key)

    def choice(self, key: str, question: str, options, default=None) -> str:
        valid = [o[0] for o in options]
        v = self._given(key)
        if v is None:
            default = self.prev.get(f"setup_{key}", default)
            if default not in valid:
                default = None
            if self.args.yes:
                if default is None:
                    raise SystemExit(f"error: --{key.replace('_', '-')} is required with --yes ({'|'.join(valid)})")
                v = default
            else:
                self._header(key)
                print(question)
                for i, (val, label, desc) in enumerate(options, 1):
                    mark = " (default)" if val == default else ""
                    print(f"  {i}) {label}{mark}" + (f" — {desc}" if desc else ""))
                while True:
                    raw = input("> ").strip().lower()
                    if not raw and default:
                        v = default
                        break
                    if raw.isdigit() and 1 <= int(raw) <= len(options):
                        v = options[int(raw) - 1][0]
                        break
                    if raw in valid:
                        v = raw
                        break
                    print(f"  please type 1-{len(options)}")
        if v not in valid:
            raise SystemExit(f"error: invalid {key}: {v!r} (choose {'|'.join(valid)})")
        self.answers[key] = v
        return v

    def text(self, key: str, question: str, default: str = "", required: bool = False) -> str:
        v = self._given(key)
        if v is None:
            default = self.prev.get(f"setup_{key}", default)
            if self.args.yes:
                v = default
            else:
                self._header(key)
                v = input(question + (f" [{default}]" if default else "") + ": ").strip() or default
        if required and not v:
            raise SystemExit(f"error: {key} is required (--{key.replace('_', '-')})")
        self.answers[key] = v
        return str(v)

    def confirm(self, question: str, default: bool = False) -> bool:
        if self.args.yes:
            return bool(self.args.install)
        raw = input(f"{question} [{'Y/n' if default else 'y/N'}] ").strip().lower()
        return default if not raw else raw.startswith("y")


# ------------------------------------------------------------- helpers
def detect_os() -> str:
    return {"darwin": "macos", "win32": "windows"}.get(sys.platform, "linux")


def has_ipv6() -> bool:
    """True when this machine can listen on IPv6. Proxy configs that add `listen [::]:...` refuse to
    start on hosts with IPv6 disabled, so those lines are only generated when it works.
    RESWATCH_IPV6=0/1 overrides the check."""
    forced = os.environ.get("RESWATCH_IPV6")
    if forced in ("0", "1"):
        return forced == "1"
    import socket
    if not socket.has_ipv6:
        return False
    try:
        with socket.socket(socket.AF_INET6, socket.SOCK_STREAM) as s:
            s.bind(("::", 0))
        return True
    except OSError:
        return False


def has_nvidia() -> bool:
    return shutil.which("nvidia-smi") is not None


def _python(os_name: str) -> str:
    exe = Path(sys.executable)
    if os_name == "windows":
        w = exe.with_name("pythonw.exe")
        if w.exists():
            return str(w)
    return str(exe)


# ------------------------------------------------------------- planning
def plan_local(a: Asker, plan: Plan, out_dir: Path, home: Path, port: int) -> None:
    os_name = a.choice("os", "Which OS is this machine?", OS_CHOICES, detect_os())
    start = a.choice("start", "How should it start?", START, "manual")
    url = f"http://localhost:{port}"
    py = _python(os_name)
    if start == "manual":
        plan.steps.append(f"Start it with:  {shlex.quote(sys.executable)} -m reswatch    then open {url}")
    elif start == "autostart":
        if os_name == "linux":
            path = home / ".config/systemd/user/reswatch.service"
            plan.files.append(Out(path, render("systemd-user.service", workdir=PROJECT, python=py, port=port),
                                  "systemd user service (starts at login)"))
            plan.commands.append(["systemctl", "--user", "daemon-reload"])
            plan.commands.append(["systemctl", "--user", "enable", "--now", "reswatch"])
            plan.steps.append(f"Status: systemctl --user status reswatch    then open {url}")
            plan.steps.append("To keep it running while logged out: loginctl enable-linger $USER")
        elif os_name == "macos":
            path = home / "Library/LaunchAgents/dev.reswatch.plist"
            plan.files.append(Out(path, render("launchagent.plist", workdir=PROJECT, python=py, port=port, home=home),
                                  "LaunchAgent (starts at login)"))
            plan.commands.append(["launchctl", "load", "-w", str(path)])
            plan.steps.append(f"Logs: ~/Library/Logs/reswatch.log    then open {url}")
        else:
            tr = f'"{py}" -m reswatch --host 127.0.0.1 --port {port}'
            cmd = ["schtasks", "/Create", "/TN", "res-watch", "/SC", "ONLOGON", "/RL", "LIMITED", "/F", "/TR", tr]
            plan.commands.append(cmd)
            plan.steps.append("Task Scheduler: the task 'res-watch' runs at logon. Create it with:\n"
                              f'      schtasks /Create /TN "res-watch" /SC ONLOGON /RL LIMITED /F /TR "{tr.replace(chr(34), chr(92) + chr(34))}"\n'
                              '    Remove it with: schtasks /Delete /TN "res-watch" /F' + f"\n    Then open {url}")
    else:
        docker_files(plan, out_dir)
        plan.steps.append("Build and run (the container sees host processes via --pid=host):\n"
                          "      docker build -t reswatch .\n"
                          f"      docker run -d --name reswatch --restart unless-stopped --pid=host --read-only --cap-drop ALL"
                          f"{user_flag()} -p 127.0.0.1:{port}:8000 -e RESWATCH_AUTH=off{gpu_run_flag()} reswatch\n"
                          f"    then open {url}  (published on 127.0.0.1 only, so no login is needed)")
    plan.config.update(host="127.0.0.1", port=port, base_path="", auth="auto", trusted_proxy=False)


def host_user() -> str:
    """uid:gid to run the container as (reads the 0600 auth.json, no root needed)."""
    if hasattr(os, "getuid"):
        return f"{os.getuid()}:{os.getgid()}"
    return ""


def user_flag() -> str:
    u = host_user()
    return f" --user {u}" if u else ""


def gpu_run_flag() -> str:
    return " --gpus all" if has_nvidia() else ""


def docker_files(plan: Plan, out_dir: Path) -> None:
    plan.files.append(Out(out_dir / "Dockerfile", render("Dockerfile", gpu_build="1" if has_nvidia() else "0"),
                          "Docker image"))
    plan.files.append(Out(out_dir / ".dockerignore", render("dockerignore"), "Docker build excludes"))


def plan_vps(a: Asker, plan: Plan, out_dir: Path, port: int, config_dir: Path, local_too: bool) -> None:
    run = a.choice("run", "How will it run on the server?", RUN, "systemd")
    proxy = a.choice("proxy", "What sits in front of it?", PROXY, "none")
    domain, https, base = "", "have", ""
    if proxy != "none":
        if proxy in ("caddy", "nginx", "traefik", "apache", "cloudflare"):
            domain = a.text("domain", "Domain name (e.g. monitor.example.com)", required=True)
        if proxy != "cloudflare":
            https = a.choice("https", "Do you already have HTTPS and a domain set up?", HTTPS, "have")
        base = normalize_base_path(a.text("base_path", "Serve under a sub-path? (e.g. /reswatch, empty = root)", ""))
    auth = a.choice("auth", "Login:", AUTH, "builtin")
    auth_mode = "on" if auth == "builtin" else "off"
    trusted = proxy != "none"
    deploy = out_dir / "deploy"
    flags = " ".join(f for f in (f"--base-path {base}" if base else "", "--trusted-proxy" if trusted else "",
                                 "--no-auth" if auth_mode == "off" else "--auth on") if f)
    user = getpass.getuser()

    # ---- how it runs
    if run == "systemd":
        plan.files.append(Out(deploy / "reswatch.service",
                              render("reswatch.service", user=user, workdir=PROJECT, python=sys.executable, port=port,
                                     flags=flags, config_dir=config_dir), "systemd service"))
        plan.steps.append("Install the service:\n"
                          f"      sudo cp {deploy / 'reswatch.service'} /etc/systemd/system/\n"
                          "      sudo systemctl daemon-reload && sudo systemctl enable --now reswatch")
    elif run in ("docker", "compose"):
        docker_files(plan, out_dir)
        if run == "compose":
            plan.files.append(Out(out_dir / "docker-compose.yml",
                                  compose_file(port, auth_mode, trusted, base, config_dir, proxy, domain),
                                  "Docker Compose service"))
            plan.steps.append(f"Start it:  cd {out_dir} && docker compose up -d --build")
        else:
            vol = f" -v {config_dir}:/config:ro" if auth_mode == "on" else ""
            plan.steps.append("Build and run (--pid=host lets the container see the host's processes):\n"
                              f"      cd {out_dir} && docker build -t reswatch .\n"
                              f"      docker run -d --name reswatch --restart unless-stopped --pid=host --read-only"
                              f" --cap-drop ALL{user_flag()} -p 127.0.0.1:{port}:8000{vol} -e RESWATCH_AUTH={auth_mode}"
                              f" -e RESWATCH_TRUSTED_PROXY={'true' if trusted else 'false'}"
                              + (f" -e RESWATCH_BASE_PATH={base}" if base else "") + f"{gpu_run_flag()} reswatch")
        plan.steps.append("Docker notes: the port is published on 127.0.0.1 only. Some per-process fields of other "
                          "users' processes may show n/a with --cap-drop ALL; add --cap-add SYS_PTRACE to see them. "
                          "GPU metrics need the NVIDIA Container Toolkit (--gpus all).")
    else:
        plan.steps.append("Run it in tmux:\n"
                          f"      tmux new -s reswatch '{sys.executable} -m reswatch --host 127.0.0.1 --port {port} {flags}'")

    # ---- what is in front
    proxy_files(plan, deploy, proxy, domain, base, port, https, run)

    # ---- login
    if auth_mode == "on":
        plan.set_password = True
        plan.steps.append(f"Login: change the password any time with  {sys.executable} -m reswatch set-password"
                          + ("  (on the Docker host; the config folder is mounted read-only)" if run in ("docker", "compose") else ""))
    else:
        plan.steps.append("Login: built-in login is OFF (--no-auth). Make sure your proxy/SSO really authenticates "
                          "every request before it reaches res-watch.")
    plan.steps.append("Firewall: allow only SSH" + (" and 80/443" if proxy not in ("none", "cloudflare") else "")
                      + ", never port " + str(port) + ", e.g.\n"
                      "      sudo ufw allow OpenSSH" + ("\n      sudo ufw allow 80,443/tcp" if proxy not in ("none", "cloudflare") else "")
                      + "\n      sudo ufw enable")
    if not local_too:
        plan.config.update(host="127.0.0.1", port=port, base_path=base, auth=auth_mode, trusted_proxy=trusted)


def compose_file(port, auth_mode, trusted, base, config_dir, proxy, domain) -> str:
    volumes = f"    volumes:\n      - {config_dir}:/config:ro   # auth.json from 'set-password'\n" if auth_mode == "on" else ""
    ports = f"    ports:\n      - \"127.0.0.1:{port}:8000\"\n"
    gpu = ("    deploy:\n      resources:\n        reservations:\n          devices:\n"
           "            - driver: nvidia\n              count: all\n              capabilities: [gpu]\n") if has_nvidia() else ""
    labels = ""
    if proxy == "traefik":
        labels = ("    labels:\n      - traefik.enable=true\n"
                  f"      - traefik.http.routers.reswatch.rule={traefik_rule(domain, base)}\n"
                  "      - traefik.http.routers.reswatch.entrypoints=websecure\n"
                  "      - traefik.http.routers.reswatch.tls.certresolver=letsencrypt\n"
                  "      - traefik.http.services.reswatch.loadbalancer.server.port=8000\n"
                  "    networks: [traefik]   # the network your Traefik container is attached to\n"
                  "\nnetworks:\n  traefik:\n    external: true\n")
    user = f"    user: \"{host_user()}\"   # same uid as the owner of auth.json\n" if host_user() else ""
    return render("docker-compose.yml", user=user, auth=auth_mode, trusted_proxy="true" if trusted else "false",
                  base_path=base, volumes=volumes, ports=ports, gpu_compose=gpu, traefik_labels=labels)


def traefik_rule(domain, base) -> str:
    rule = f"Host(`{domain}`)"
    return rule + (f" && PathPrefix(`{base}`)" if base else "")


def proxy_files(plan: Plan, deploy: Path, proxy, domain, base, port, https, run) -> None:
    loc = f"{base}/" if base else "/"
    if proxy == "none":
        plan.steps.append("Connect through an SSH tunnel from your computer:\n"
                          f"      ssh -N -L {port}:127.0.0.1:{port} user@your-server\n"
                          f"    then open http://localhost:{port}{base}/")
        return
    url = f"https://{domain or 'your-domain'}{base}/"
    if proxy == "caddy":
        body = (f"    handle {base}* {{\n        reverse_proxy 127.0.0.1:{port}\n    }}" if base
                else f"    reverse_proxy 127.0.0.1:{port}")
        plan.files.append(Out(deploy / "Caddyfile", render("Caddyfile", domain=domain, caddy_body=body), "Caddy site"))
        plan.steps.append("Caddy: add deploy/Caddyfile to /etc/caddy/Caddyfile, then sudo systemctl reload caddy")
        if https == "docs":
            plan.steps.append(f"HTTPS: point a DNS A/AAAA record for {domain} at this server and open ports 80/443. "
                              "Caddy then gets the certificate automatically.")
    elif proxy == "nginx":
        redirect = f"\n    location = {base} {{ return 301 {base}/; }}\n" if base else ""
        v6 = has_ipv6()
        plan.files.append(Out(deploy / "nginx.conf", render(
            "nginx.conf", domain=domain, location=loc, port=port, nginx_base_redirect=redirect,
            listen6_80="    listen [::]:80;\n" if v6 else "    # listen [::]:80;      (IPv6 was not available when this was generated)\n",
            listen6_443="    listen [::]:443 ssl;\n" if v6 else "    # listen [::]:443 ssl; (IPv6 was not available when this was generated)\n"),
            "nginx site"))
        plan.steps.append("nginx: install deploy/nginx.conf (instructions at the top of the file)")
        if https == "docs":
            plan.steps.append(f"HTTPS: point DNS for {domain} at this server, then\n"
                              "      sudo apt install certbot python3-certbot-nginx\n"
                              f"      sudo certbot certonly --nginx -d {domain}\n"
                              "    certbot renews automatically; reload nginx after the first certificate.")
    elif proxy == "apache":
        plan.files.append(Out(deploy / "apache.conf", render("apache.conf", domain=domain, location=loc, port=port),
                              "Apache site"))
        plan.steps.append("Apache: install deploy/apache.conf (instructions at the top of the file)")
        if https == "docs":
            plan.steps.append(f"HTTPS: point DNS for {domain} at this server, then\n"
                              "      sudo apt install certbot python3-certbot-apache\n"
                              f"      sudo certbot certonly --apache -d {domain}")
    elif proxy == "traefik":
        if run != "compose":
            plan.files.append(Out(deploy / "traefik-dynamic.yml",
                                  render("traefik-dynamic.yml", traefik_rule=traefik_rule(domain, base), port=port,
                                         cert_resolver="letsencrypt"), "Traefik route (file provider)"))
            plan.steps.append("Traefik: load deploy/traefik-dynamic.yml with the file provider")
        else:
            plan.steps.append("Traefik: routing labels are in docker-compose.yml (adjust the network name)")
        if https == "docs":
            plan.steps.append("HTTPS: define a Let's Encrypt resolver named 'letsencrypt' in Traefik's static config:\n"
                              "      certificatesResolvers:\n        letsencrypt:\n          acme:\n"
                              "            email: you@example.com\n            storage: /letsencrypt/acme.json\n"
                              "            httpChallenge: { entryPoint: web }")
    elif proxy == "cloudflare":
        cf_path = f"    path: ^{base}/\n" if base else ""
        plan.files.append(Out(deploy / "cloudflared.yml", render("cloudflared.yml", domain=domain, port=port,
                                                                   cf_path=cf_path), "Cloudflare Tunnel config"))
        plan.steps.append("Cloudflare Tunnel: follow the steps at the top of deploy/cloudflared.yml")
        url = f"https://{domain}{base}/"
    else:
        plan.steps.append("Other proxy: forward HTTPS traffic for your site to http://127.0.0.1:"
                          f"{port}{loc}, keep the path ({loc}) unchanged, enable WebSocket upgrade for {base}/ws, "
                          "and set X-Forwarded-For / X-Forwarded-Proto.")
        if https == "docs":
            plan.steps.append("HTTPS: point DNS at the server and get a certificate (e.g. Let's Encrypt via certbot) "
                              "for your proxy.")
    plan.steps.append(f"Open {url}")


# -------------------------------------------------------------- writing
def write_files(a: Asker, files: list[Out]) -> list[Path]:
    """Write files, printing "[i/N] wrote|unchanged|skipped <path>" for each."""
    written, n = [], len(files)
    width = len(str(n))
    for i, f in enumerate(files, 1):
        tag = f"  [{i:>{width}}/{n}]"
        if f.path.exists():
            old = f.path.read_text(encoding="utf-8", errors="replace")
            if old == f.content:
                print(f"{tag} unchanged  {f.path}")
                continue
            if f.ask and not a.args.yes:
                diff = difflib.unified_diff(old.splitlines(), f.content.splitlines(), str(f.path), "new", lineterm="")
                print("\n".join(list(diff)[:80]))
                if not a.confirm(f"Overwrite {f.path}?", True):
                    print(f"{tag} skipped    {f.path}")
                    continue
            if f.ask:
                shutil.copy2(f.path, f.path.with_name(f.path.name + ".bak"))
        f.path.parent.mkdir(parents=True, exist_ok=True)
        f.path.write_text(f.content, encoding="utf-8")
        if f.mode is not None:
            os.chmod(f.path, f.mode)
        print(f"{tag} wrote      {f.path}  ({f.what})")
        written.append(f.path)
    return written


def run(args) -> int:
    config_dir = Path(args.config_dir).expanduser() if args.config_dir else default_config_dir()
    home = Path(args.home) if getattr(args, "home", None) else Path.home()
    out_dir = Path(args.output_dir).resolve()
    cfg_path = config_dir / "config.toml"
    previous = read_toml(cfg_path)
    a = Asker(args, previous)
    if not args.yes:
        print("res-watch setup — answer a few questions; only matching files are generated.\n"
              f"(running on {platform.system()} {platform.release()}, Python {platform.python_version()})")

    where = a.choice("where", "Where will you run res-watch?", WHERE, "local")
    port = int(a._given("port") or previous.get("port") or 8000)
    plan = Plan()
    if where == "vps":
        plan_vps(a, plan, out_dir, port, config_dir, local_too=False)
    elif where == "both":
        # Server files contain server paths (python, project dir, user), so they are generated by
        # running setup ON the server. Ask the questions now and print the exact command for it.
        if not args.yes:
            print("\n— Server side (you'll run one command on the server afterwards) —")
        plan_vps(a, Plan(), out_dir, port, config_dir, local_too=True)
        if not args.yes:
            print("\n— This machine (local) —")
        plan_local(a, plan, out_dir, home, port)
        flags = " ".join(f"--{k.replace('_', '-')} {shlex.quote(str(v))}" for k, v in a.answers.items()
                         if k in ("run", "proxy", "https", "domain", "base_path", "auth") and v not in (None, ""))
        plan.steps.append("On the server: clone this repo, then run\n"
                          f"      ./setup.sh --where vps --port {port} {flags}\n"
                          "    It generates the server files with the server's own paths and sets the login there.")
    else:
        plan_local(a, plan, out_dir, home, port)

    cfg = dict(plan.config)
    cfg.update({f"setup_{k}": v for k, v in a.answers.items() if v not in (None, "")})
    cfg_text = toml_text(cfg, header=HEADER + "\n# Read by `python -m reswatch`; CLI flags and RESWATCH_* env vars override it.")
    files = plan.files + [Out(cfg_path, cfg_text, "settings + your answers", ask=False)]
    print(f"\nWriting {len(files)} file{'s' if len(files) != 1 else ''}:" + ("" if plan.files else "  (no deploy files needed for these answers)"))
    write_files(a, files)

    if plan.set_password:
        from .auth import auth_file
        if auth_file(config_dir).exists():
            print(f"\nA login already exists in {auth_file(config_dir)} (keep it, or run set-password to change it).")
        elif args.yes:
            plan.steps.insert(0, f"Set the admin password first:  {sys.executable} -m reswatch set-password")
        else:
            print("\nCreate the admin login now:")
            from .__main__ import main as cli_main
            cli_main(["set-password", "--config-dir", str(config_dir)])

    if plan.commands:
        shown = "\n".join("  " + " ".join(shlex.quote(x) for x in c) for c in plan.commands)
        current_os = detect_os()
        target_os = a.answers.get("os", current_os)
        if target_os != current_os:
            print(f"\nRun these on the {target_os} machine:\n{shown}")
        elif a.confirm(f"\nEnable autostart now? This runs:\n{shown}\n", True):
            for c in plan.commands:
                r = subprocess.run(c)
                if r.returncode != 0:
                    print(f"  command failed ({r.returncode}): {' '.join(c)}")
                    break
        else:
            print(f"Skipped. To enable later run:\n{shown}")

    print("\nNext steps:")
    for i, s in enumerate(plan.steps, 1):
        print(f"  {i}. {s}")
    print("\nDetails: README.md ('Running locally' / 'Running on a VPS'). Re-run `python -m reswatch setup` any time.")
    return 0
